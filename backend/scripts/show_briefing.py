"""Write docs/AGENT_BRIEFING.md: exactly what an agent reads, generated from the code.

    ./venv/bin/python scripts/show_briefing.py          # rewrite the file
    ./venv/bin/python scripts/show_briefing.py --check  # fail if the file is stale
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from agents.briefing import briefing, turn_prompt
from engine.facade import Facade

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "docs", "AGENT_BRIEFING.md")


def render() -> str:
    f = Facade()
    press = [{"phase": f.phase, "sender": "FRANCE", "to": "GERMANY", "text": "Stay out of Burgundy and I stay out of Ruhr?"}]
    sample = turn_prompt(power="GERMANY", state=f.state("GERMANY"), legal=f.legal_orders("GERMANY"),
                         seconds_left=74, submitted={"ITALY"}, waiting={"AUSTRIA", "ENGLAND", "FRANCE", "GERMANY",
                                                                        "RUSSIA", "TURKEY"},
                         press=press, notes=[], last_result=None,
                         feedback=["Submission refused: 'A MUN - PAR' is not one of your legal orders"],
                         final_call=False)
    b = briefing("GERMANY")
    return "\n".join([
        "# What an agent reads",
        "",
        "Generated by `backend/scripts/show_briefing.py` from `backend/agents/briefing.py`.",
        "Do not edit by hand; `check.sh` fails if this file is out of date.",
        "",
        f"## 1. The briefing (system prompt, once per game, about {len(b) // 4:,} tokens)",
        "",
        "Shown for Germany. The only thing that changes between powers is the name.",
        "",
        "```text", b.rstrip(), "```",
        "",
        f"## 2. A turn prompt (every time the agent is asked to act, about {len(sample) // 4:,} tokens at the start)",
        "",
        "Spring 1901, Germany, with one message received and one refused submission.",
        "It grows as messages and last phase's results accumulate.",
        "",
        "```text", sample.rstrip(), "```",
        "",
    ])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("docs/AGENT_BRIEFING.md is stale: run scripts/show_briefing.py")
        print("docs/AGENT_BRIEFING.md is current")
    else:
        open(OUT, "w").write(text)
        print(f"wrote {os.path.normpath(OUT)}")
